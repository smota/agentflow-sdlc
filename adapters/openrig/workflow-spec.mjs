// Generates and checks the OpenRig workflow spec that runs AgentFlow phases 1-8.
// Source of truth: lib/core/phase-graph.mjs (phases, returns, cap) and manifests/seats.json (seats).
// Pure: no file or process I/O. scripts/validate-openrig-workflow.mjs reads, writes and runs `rig`.
import YAML from 'yaml'
import { MAX_RETURN_CYCLES, PHASES, RETURNS } from '../../lib/core/phase-graph.mjs'
import { canonicalSeat } from '../../lib/core/seat-table.mjs'

// A deliberate strict subset of the OpenRig workflow parser keys (checked against 0.7.1; the bundle
// requires >= 0.7.6). Keys this spec does not use are left out so they cannot slip in unreviewed.
// `rig workflow validate` (the --rig check) stays the authority.
export const OPENRIG_WORKFLOW_KEYS = Object.freeze({
  top: [
    'id',
    'version',
    'objective',
    'target',
    'entry',
    'roles',
    'steps',
    'invariants',
    'closure',
    'loop_guards',
    'exception_routing',
    'coordination_terminal_turn_rule',
    'context_refs',
  ],
  step: [
    'id',
    'actor_role',
    'objective',
    'allowed_exits',
    're_present_after_seconds',
    're_present_max_seconds',
    'next_hop',
    'harness',
    'host',
    'gate',
    'depends_on',
    'acceptance',
  ],
  role: ['preferred_targets'],
  nextHop: ['on'],
  gate: ['target'],
  exit: ['handoff', 'waiting', 'done', 'failed'],
})

export const WORKFLOW_ID = 'agentflow-delivery'
export const GENERATED_HEADER =
  '# GENERATED by `node scripts/validate-openrig-workflow.mjs --write` from lib/core/phase-graph.mjs and manifests/seats.json. Do not edit.'

// Workflow role per AgentFlow phase role. Phase 0 (product manager) is not a workflow step.
const WORKFLOW_ROLE = Object.freeze({
  analyst: 'analyst',
  architect: 'architect',
  'implementation-planner': 'architect',
  developer: 'builder',
  tester: 'tester',
  reviewer: 'reviewer',
  'technical-writer': 'architect',
  'pr-readiness': 'architect',
})
const STEP_SLUG = Object.freeze({
  analyst: 'analyst',
  architect: 'architect',
  'implementation-planner': 'planner',
  developer: 'developer',
  tester: 'tester',
  reviewer: 'reviewer',
  'technical-writer': 'writer',
  'pr-readiness': 'readiness',
})
const STEP_OBJECTIVE = Object.freeze({
  'implementation-planner': 'Phase 3 implementation planner',
  'technical-writer': 'Phase 7 technical writer',
  'pr-readiness': 'Phase 8 PR readiness; wait on external:merge',
})
const STEP_EXITS = Object.freeze({
  1: ['handoff', 'failed'],
  2: ['handoff', 'failed'],
  3: ['handoff', 'failed'],
  4: ['handoff', 'failed'],
  5: ['handoff', 'failed'],
  6: ['handoff', 'waiting', 'failed'],
  7: ['handoff', 'failed'],
  8: ['handoff', 'waiting', 'failed'],
})
const CLEANUP_EXITS = Object.freeze(['done', 'waiting', 'failed'])

const stepId = (phase) => `p${phase.phase}-${STEP_SLUG[phase.role]}`
const seatsOf = (phase) => phase.seats ?? [phase.seat]
const targetOf = (seat) => `${seat.replace('.', '-')}@{rig}`
const seatOf = (target) =>
  String(target)
    .replace(/@\{rig\}$/, '')
    .replace('-', '.')
const workflowPhases = (phases) => phases.filter((item) => item.phase >= 1)

/** One `failed` successor per step: the first return target that is itself a step (phase >= 1). */
export function mappedReturns(returns = RETURNS) {
  const mapped = {}
  for (const [from, targets] of Object.entries(returns)) {
    const to = targets.find((target) => target >= 1)
    if (to !== undefined) mapped[Number(from)] = to
  }
  return mapped
}

/** Instance backstop: forward hops plus the worst case of `maxReturnCycles` per mapped loop. */
export function expectedMaxHops({
  phases = PHASES,
  returns = RETURNS,
  mapped = mappedReturns(returns),
  maxReturnCycles = MAX_RETURN_CYCLES,
}) {
  const loops = Object.entries(mapped).reduce(
    (sum, [from, to]) => sum + (Number(from) - Number(to) + 1),
    0,
  )
  // A legal return with no step edge (4 -> 1) still happens when the planner's rework is sent past
  // the planner: 4 -> 3 -> 1, then 1, 2, 3, 4 again. Count the extra hop of the detour too.
  const detours = Object.entries(returns).reduce((sum, [from, targets]) => {
    return (
      sum +
      targets
        .filter((to) => to >= 1 && to !== mapped[from])
        .reduce((total, to) => total + (Number(from) - to + 2), 0)
    )
  }, 0)
  return workflowPhases(phases).length + maxReturnCycles * (loops + detours)
}

export function buildDeliveryWorkflowSpec({
  seatTable,
  phases = PHASES,
  returns = RETURNS,
  maxReturnCycles = MAX_RETURN_CYCLES,
}) {
  const flow = workflowPhases(phases)
  const roles = {}
  for (const phase of flow) {
    const seats = seatsOf(phase)
      .map((seat) => canonicalSeat(seatTable, seat) ?? seat)
      .sort((a, b) => (a === 'dev.build' ? -1 : b === 'dev.build' ? 1 : 0))
    roles[WORKFLOW_ROLE[phase.role]] = { preferred_targets: seats.map(targetOf) }
  }
  const mapped = mappedReturns(returns)
  const steps = flow.map((phase) => {
    const step = {
      id: stepId(phase),
      actor_role: WORKFLOW_ROLE[phase.role],
      objective: STEP_OBJECTIVE[phase.role] ?? `Phase ${phase.phase} ${phase.role}`,
    }
    step.allowed_exits = [...STEP_EXITS[phase.phase]]
    const to = mapped[phase.phase]
    if (to !== undefined) {
      step.next_hop = { on: { failed: stepId(phases.find((item) => item.phase === to)) } }
    }
    return step
  })
  steps.push({
    id: 'cleanup',
    actor_role: 'architect',
    objective: 'Remove the slice worktree and release the claim (agentflow-sdlc bridge cleanup)',
    allowed_exits: [...CLEANUP_EXITS],
  })
  return {
    workflow: {
      id: WORKFLOW_ID,
      version: 1,
      objective: 'Carry one AgentFlow slice from analysis to merged, evidenced delivery.',
      entry: { role: WORKFLOW_ROLE[flow[0].role] },
      roles,
      steps,
      loop_guards: { max_hops: expectedMaxHops({ phases, returns, mapped, maxReturnCycles }) },
      exception_routing: {
        default: 'orchestrator',
        orchestrator_role: 'architect',
        classes: { unmapped_failed: 'human_only', stuck_overdue: 'human_only' },
      },
    },
  }
}

export function renderWorkflowSpecYaml(spec) {
  return `${GENERATED_HEADER}\n${YAML.stringify(spec, { lineWidth: 0 })}`
}

function unknownKeys(object, allowed, where) {
  return Object.keys(object ?? {})
    .filter((key) => !allowed.includes(key))
    .map((key) => `${where}: unknown key "${key}"`)
}

function hasCycle(steps) {
  const index = new Map(steps.map((step, i) => [step.id, i]))
  const edges = steps.map((step, i) => {
    const out = Object.values(step.next_hop?.on ?? {})
      .map((target) => index.get(target))
      .filter((target) => target !== undefined)
    if (i + 1 < steps.length) out.push(i + 1)
    return out
  })
  const state = new Array(steps.length).fill(0)
  const visit = (node) => {
    state[node] = 1
    for (const next of edges[node]) {
      if (state[next] === 1 || (state[next] === 0 && visit(next))) return true
    }
    state[node] = 2
    return false
  }
  return steps.some((_, node) => state[node] === 0 && visit(node))
}

/** Local mirror of the OpenRig parser and validator rules that CI can check without a daemon. */
export function workflowStructureProblems(doc) {
  const problems = []
  const keys = Object.keys(doc ?? {})
  if (keys.length !== 1 || keys[0] !== 'workflow') {
    return ['spec must have the single root key "workflow"']
  }
  const wf = doc.workflow
  const { top, step: stepKeys, role: roleKeys, nextHop, gate, exit } = OPENRIG_WORKFLOW_KEYS
  problems.push(...unknownKeys(wf, top, 'workflow'))
  for (const key of ['id', 'objective', 'entry', 'roles', 'steps']) {
    if (wf[key] === undefined) problems.push(`workflow: missing "${key}"`)
  }
  const roles = wf.roles ?? {}
  const steps = Array.isArray(wf.steps) ? wf.steps : []
  if (!Array.isArray(wf.steps) || steps.length === 0) problems.push('workflow.steps must be a list')
  for (const [name, role] of Object.entries(roles)) {
    problems.push(...unknownKeys(role, roleKeys, `role ${name}`))
    if (!Array.isArray(role?.preferred_targets) || role.preferred_targets.length === 0) {
      problems.push(`role ${name}: preferred_targets must be a non-empty list`)
    }
  }
  if (wf.entry?.role && !roles[wf.entry.role])
    problems.push(`entry: unknown role "${wf.entry.role}"`)
  const ids = new Set()
  for (const step of steps) {
    const where = `step ${step?.id ?? '?'}`
    problems.push(...unknownKeys(step, stepKeys, where))
    if (!step?.id) problems.push(`${where}: missing id`)
    else if (ids.has(step.id)) problems.push(`${where}: duplicate id`)
    ids.add(step?.id)
    if (!roles[step?.actor_role])
      problems.push(`${where}: unknown actor_role "${step?.actor_role}"`)
    for (const value of step?.allowed_exits ?? []) {
      if (!exit.includes(value)) problems.push(`${where}: unknown exit "${value}"`)
    }
    problems.push(...unknownKeys(step?.next_hop, nextHop, `${where} next_hop`))
    problems.push(...unknownKeys(step?.gate, gate, `${where} gate`))
    for (const [on, target] of Object.entries(step?.next_hop?.on ?? {})) {
      if (!exit.includes(on)) problems.push(`${where}: next_hop.on key "${on}" is not an exit`)
      if (!steps.some((other) => other.id === target)) {
        problems.push(`${where}: next_hop.on.${on} targets unknown step "${target}"`)
      }
    }
  }
  problems.push(...unknownKeys(wf.loop_guards, ['max_hops'], 'loop_guards'))
  problems.push(
    ...unknownKeys(
      wf.exception_routing,
      ['default', 'orchestrator_role', 'classes'],
      'exception_routing',
    ),
    ...unknownKeys(
      wf.exception_routing?.classes,
      ['unmapped_failed', 'stuck_overdue'],
      'exception_routing.classes',
    ),
  )
  if (steps.length > 0 && hasCycle(steps)) {
    const hops = wf.loop_guards?.max_hops
    if (!Number.isInteger(hops) || hops < 1) {
      problems.push('workflow has a routing cycle: loop_guards.max_hops must be an integer >= 1')
    }
  }
  return problems
}

/** Rules AgentFlow adds on top of the OpenRig structure: the spec must agree with the phase graph. */
export function workflowSpecProblems(
  doc,
  { seatTable, phases = PHASES, returns = RETURNS, maxReturnCycles = MAX_RETURN_CYCLES },
) {
  const wf = doc?.workflow
  if (!wf) return ['spec must have the single root key "workflow"']
  const problems = []
  const flow = workflowPhases(phases)
  const steps = (wf.steps ?? []).filter((step) => step.id !== 'cleanup')
  const roleSeats = (name) =>
    (wf.roles?.[name]?.preferred_targets ?? []).map((target) => seatOf(target))

  if (steps.length !== flow.length || flow.some((phase, i) => steps[i]?.id !== stepId(phase))) {
    problems.push(
      `steps ${steps.map((s) => s.id).join(',')} do not match phases ${flow.map(stepId).join(',')}`,
    )
  }
  flow.forEach((phase, i) => {
    const step = steps[i]
    if (!step) return
    const want = seatsOf(phase).map((seat) => canonicalSeat(seatTable, seat) ?? seat)
    const got = roleSeats(step.actor_role)
    if (JSON.stringify([...got].sort()) !== JSON.stringify([...want].sort())) {
      problems.push(
        `step ${step.id}: seats ${got.join(',') || 'none'} do not match phase ${phase.phase} seats ${want.join(',')}`,
      )
    }
  })

  const mapped = mappedReturns(returns)
  for (const step of steps) {
    const phase = flow.find((item) => stepId(item) === step.id)
    const failed = step.next_hop?.on?.failed
    const target = flow.find((item) => stepId(item) === failed)
    if (failed && (!target || !(returns[phase?.phase] ?? []).includes(target.phase))) {
      problems.push(`step ${step.id}: on.failed "${failed}" is not a legal return of its phase`)
    }
    if (phase && !failed && mapped[phase.phase] !== undefined) {
      problems.push(
        `step ${step.id}: missing on.failed for the return to phase ${mapped[phase.phase]}`,
      )
    }
    if (failed && target && mapped[phase.phase] !== target.phase) {
      problems.push(`step ${step.id}: on.failed must return to phase ${mapped[phase.phase]}`)
    }
  }

  const want = expectedMaxHops({ phases, returns, mapped, maxReturnCycles })
  if (wf.loop_guards?.max_hops !== want) {
    problems.push(`loop_guards.max_hops is ${wf.loop_guards?.max_hops}, expected ${want}`)
  }
  // Literal checks, independent of the generator helpers above.
  const route = wf.exception_routing
  if (!route?.default) problems.push('exception_routing.default is required')
  for (const name of ['unmapped_failed', 'stuck_overdue']) {
    if (route?.classes?.[name] !== 'human_only') {
      problems.push(`exception_routing.classes.${name} must be human_only`)
    }
  }
  const all = wf.steps ?? []
  const cleanup = all.filter((step) => step.id === 'cleanup')
  if (cleanup.length !== 1 || all.at(-1)?.id !== 'cleanup') {
    problems.push('cleanup must be the single, last step')
  }
  if (cleanup[0]?.actor_role !== 'architect') problems.push('cleanup must be owned by architect')
  for (const exit of ['failed']) {
    if (cleanup[0] && !(cleanup[0].allowed_exits ?? []).includes(exit)) {
      problems.push(`cleanup must allow ${exit}`)
    }
  }
  if (wf.entry?.role !== all[0]?.actor_role) {
    problems.push(`entry.role "${wf.entry?.role}" must equal the first step's actor_role`)
  }
  for (const step of all) {
    const exits = step.allowed_exits
    if (step.id === 'cleanup') continue
    if (!Array.isArray(exits) || exits.length === 0) {
      problems.push(`step ${step.id}: allowed_exits must be explicit`)
    } else if (exits.includes('done')) {
      problems.push(`step ${step.id}: only cleanup may allow done`)
    }
    for (const on of Object.keys(step.next_hop?.on ?? {})) {
      if (on !== 'failed') problems.push(`step ${step.id}: next_hop.on.${on} is not a legal route`)
    }
    if (step.next_hop?.on?.failed && !(exits ?? []).includes('failed')) {
      problems.push(`step ${step.id}: allowed_exits must include failed`)
    }
  }
  if (!(all.find((step) => step.id === 'p6-reviewer')?.allowed_exits ?? []).includes('failed')) {
    problems.push('step p6-reviewer must allow failed')
  }

  // A review can never be owned by a seat that built the item.
  const builders = new Set(roleSeats(wf.steps?.find((s) => s.id === 'p4-developer')?.actor_role))
  const reviewers = roleSeats(wf.steps?.find((s) => s.id === 'p6-reviewer')?.actor_role)
  for (const seat of reviewers.filter((item) => builders.has(item))) {
    problems.push(`seat ${seat} owns both the developer and the reviewer step`)
  }
  const builderPhase = new Set(phases.filter((p) => p.role === 'developer').flatMap(seatsOf))
  for (const seat of phases.filter((p) => p.role === 'reviewer').flatMap(seatsOf)) {
    if (builderPhase.has(seat)) problems.push(`phase graph gives seat ${seat} build and review`)
  }
  return problems
}
