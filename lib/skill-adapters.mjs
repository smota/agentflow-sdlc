import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { createHash } from 'node:crypto'

export const SDLC_SKILLS = ['sdlc-definition', 'sdlc-migration', 'sdlc-audit']
export const HARNESS_TARGETS = {
  'claude-code': '.claude/skills',
  pi: '.pi/skills',
  agy: '.agents/skills',
  codex: '.agents/skills',
}

export function syncSkillAdapters({ packageRoot, targetDir, harness = 'all', write = false } = {}) {
  const harnesses = harness === 'all' ? Object.keys(HARNESS_TARGETS) : String(harness).split(',')
  const planned = []
  for (const name of SDLC_SKILLS) {
    const source = join(packageRoot, 'skills', name, 'SKILL.md')
    const content = readFileSync(source, 'utf8')
    for (const item of harnesses) {
      const root = HARNESS_TARGETS[item]
      if (!root) throw new Error(`Unknown harness: ${item}`)
      const target = join(targetDir, root, name, 'SKILL.md')
      const generated = renderAdapter({ content, source: `skills/${name}/SKILL.md`, harness: item })
      const status =
        existsSync(target) && readFileSync(target, 'utf8') === generated ? 'unchanged' : 'planned'
      planned.push({
        skill: name,
        harness: item,
        source: `skills/${name}/SKILL.md`,
        target,
        status,
        hash: hash(generated),
      })
      if (write && status !== 'unchanged') {
        mkdirSync(dirname(target), { recursive: true })
        writeFileSync(target, generated)
      }
    }
  }
  const manifestPath = join(targetDir, '.agentflow-adapters.lock.json')
  if (write)
    writeFileSync(manifestPath, `${JSON.stringify({ version: 1, entries: planned }, null, 2)}\n`)
  return { ok: true, mode: write ? 'apply' : 'dry-run', entries: planned, manifestPath }
}

export function adapterStatus({ packageRoot, targetDir, harness = 'all' } = {}) {
  const result = syncSkillAdapters({ packageRoot, targetDir, harness, write: false })
  return {
    ...result,
    stale: result.entries.filter((entry) => entry.status !== 'unchanged'),
  }
}

function renderAdapter({ content, source }) {
  return `<!-- GENERATED BY AgentFlow SDLC. Do not edit. Source: ${source}. -->\n${content}\n\n## Generated adapter note\n\nThis harness-specific copy is generated from harness-neutral AgentFlow SDLC product source. Regenerate with:\n\n\`\`\`bash\nagentflow-sdlc skills sync --harness all\n\`\`\`\n\nRun deterministic validators through the CLI; do not duplicate validation logic in this adapter.\n`
}

function hash(value) {
  return createHash('sha256').update(value).digest('hex')
}
