import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { createHash } from 'node:crypto'
import { loadSkillCatalog } from './skill-catalog.mjs'

export const HARNESS_TARGETS = {
  'claude-code': '.claude/skills',
  pi: '.pi/skills',
  agy: '.agents/skills',
  codex: '.agents/skills',
}

export function syncSkillAdapters({ packageRoot, targetDir, harness = 'all', write = false } = {}) {
  const harnesses = harness === 'all' ? Object.keys(HARNESS_TARGETS) : String(harness).split(',')
  const catalog = loadSkillCatalog(packageRoot)
  const planned = []
  for (const skill of catalog.skills) {
    const adapterName = `${catalog.namespace}-${skill.role}`
    const sourceRoot = join(packageRoot, skill.source)
    const files = listFiles(sourceRoot)
    for (const item of harnesses) {
      const root = HARNESS_TARGETS[item]
      if (!root) throw new Error(`Unknown harness: ${item}`)
      for (const source of files) {
        const relativePath = relative(sourceRoot, source)
        const target = join(targetDir, root, adapterName, relativePath)
        const content = readFileSync(source, 'utf8')
        const generated =
          relativePath === 'SKILL.md'
            ? renderAdapter({ content, source: `${skill.source}/SKILL.md`, adapterName })
            : content
        const status =
          existsSync(target) && readFileSync(target, 'utf8') === generated ? 'unchanged' : 'planned'
        planned.push({
          skill: skill.role,
          adapterName,
          qualifiedName: skill.qualifiedName,
          harness: item,
          source: `${skill.source}/${relativePath.replaceAll('\\', '/')}`,
          target,
          status,
          hash: hash(generated),
        })
        if (write && status !== 'unchanged') {
          mkdirSync(dirname(target), { recursive: true })
          writeFileSync(target, generated)
        }
      }
    }
  }
  const manifestPath = join(targetDir, '.agentflow-adapters.lock.json')
  if (write)
    writeFileSync(
      manifestPath,
      `${JSON.stringify({ version: 2, namespace: catalog.namespace, entries: planned }, null, 2)}\n`,
    )
  return { ok: true, mode: write ? 'apply' : 'dry-run', entries: planned, manifestPath }
}

export function adapterStatus({ packageRoot, targetDir, harness = 'all' } = {}) {
  const result = syncSkillAdapters({ packageRoot, targetDir, harness, write: false })
  return {
    ...result,
    stale: result.entries.filter((entry) => entry.status !== 'unchanged'),
  }
}

function renderAdapter({ content, source, adapterName }) {
  const frontmatter = content.match(/^---\r?\n[\s\S]*?\r?\n---/)
  if (!frontmatter) throw new Error(`Skill source lacks frontmatter: ${source}`)
  const adapterFrontmatter = frontmatter[0].replace(/^name:\s*[^\r\n]+$/m, `name: ${adapterName}`)
  const body = content.slice(frontmatter[0].length).replace(/^\r?\n/, '')
  return `${adapterFrontmatter}\n<!-- GENERATED BY AgentFlow SDLC. Do not edit. Source: ${source}. -->\n${body.trimEnd()}\n\n## Generated adapter note\n\nThis flat harness adapter uses the standards-safe \`${adapterName}\` name for \`agentflow:${adapterName.slice('agentflow-'.length)}\`. Regenerate with \`agentflow-sdlc skills sync --harness all\`.\n`
}

function listFiles(directory) {
  const files = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) files.push(...listFiles(path))
    else files.push(path)
  }
  return files.sort()
}

function hash(value) {
  return createHash('sha256').update(value).digest('hex')
}
